"""The ``sky130_magic`` KLayout library."""

from ._kl import db
from .pcell import make_pcell

LIBRARY_NAME = "sky130_magic"


class Sky130MagicLibrary(db.Library):
    """One PCell per Magic device. Not bound to a technology: a library bound
    to sky130A would be invisible to layouts that have no technology set."""

    def __init__(self, manifest, state):
        super().__init__()
        self.description = "sky130A devices generated by Magic (%d PCells)" % len(manifest.devices)
        self.layout().dbu = 0.001
        self.pcell_names = []
        for spec in manifest.devices:
            self.layout().register_pcell(spec.name, make_pcell(spec, state))
            self.pcell_names.append(spec.name)
        self.register(LIBRARY_NAME)
